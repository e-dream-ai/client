#!/usr/bin/env python3
"""
Writes client_generic/MSVC/edream_build_version_generated.h, the version the Windows
app reports (Settings, About, the server) and that release.py packages.

Run before every compile by the EdreamGenerateBuildVersion target in
electricsheep.vcxproj, so Visual Studio builds work from a fresh clone and are always
current (#633). build.py passes its -v through as the EdreamVersion MSBuild property.

  version   --version X.Y.Z if given (a release build); otherwise the latest git tag
  revision  git describe --tags --always --dirty, e.g. 0.16.1-12-g4aeae8cf-dirty,
            as the Mac's generate_builddata.sh does
  source    "cli" when --version was given, else "git-tag"; release.py only packages
            "cli" builds
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


def git(repo: Path, *args: str) -> str:
    try:
        r = subprocess.run(
            ["git", "-C", str(repo), *args], capture_output=True, text=True, timeout=30
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return ""
    return r.stdout.strip() if r.returncode == 0 else ""


def normalize_version(value: str) -> str:
    """'v0.16.2' -> '0.16.2'."""
    v = value.strip()
    if v.lower().startswith("v") and len(v) > 1 and (v[1].isdigit() or v[1] == "."):
        v = v[1:].lstrip()
    return v


def c_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--version", default="", help="Release version, e.g. 0.16.2.")
    args = parser.parse_args()

    client_generic = Path(__file__).resolve().parent.parent
    repo = client_generic.parent
    out_path = client_generic / "MSVC" / "edream_build_version_generated.h"

    explicit = normalize_version(args.version)
    if explicit:
        version, source = explicit, "cli"
    else:
        version, source = git(repo, "describe", "--tags", "--abbrev=0") or "0.0.0", "git-tag"
    revision = git(repo, "describe", "--tags", "--always", "--dirty") or "unknown"
    date = datetime.now(timezone.utc).strftime("%a %b %d %H:%M:%S UTC %Y")

    out_path.write_text(
        "#pragma once\n"
        "/* Generated by client_generic/WinBuild/generate_build_version.py; do not edit. */\n"
        "\n"
        f'#define EDREAM_BUILD_VERSION_SEMVER "{c_string(version)}"\n'
        f'#define EDREAM_BUILD_VERSION_SOURCE "{source}"\n'
        f'#define EDREAM_BUILD_GIT_REVISION "{c_string(revision)}"\n'
        f'#define EDREAM_BUILD_DATE_UTC "{c_string(date)}"\n',
        encoding="utf-8",
    )
    print(f"Build version {version} ({source}), revision {revision} -> {out_path.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
